//! JSON Schema bundle + manifest (from dump-schemas.ts) -> Rust source for the t3_api crate.
//!
//! Usage: t3-typify-gen <schema-dir> <out-dir>
//!
//! Writes `types.rs` (all wire types, via typify) and `methods.rs` (RPC + HTTP method
//! tables implementing the hand-written `RpcMethod` / `HttpEndpoint` traits).

use std::{collections::BTreeMap, fmt::Write as _, fs, path::PathBuf};

use anyhow::{Context, Result, bail};
use schemars::schema::{RootSchema, Schema};
use serde::Deserialize;
use typify::{TypeSpace, TypeSpaceSettings};

#[derive(Deserialize)]
#[serde(tag = "kind", rename_all = "lowercase")]
enum TypeRef {
    Ref {
        def: String,
        /// Root is `X | null` (nullability lives at the use site, see dump-schemas.ts).
        #[serde(default)]
        nullable: bool,
    },
    Void,
    Never,
}

#[derive(Deserialize)]
struct RpcEntry {
    tag: String,
    stream: bool,
    payload: TypeRef,
    success: TypeRef,
    error: TypeRef,
}

#[derive(Deserialize)]
struct Payload {
    #[serde(rename = "contentType")]
    content_type: String,
    #[serde(rename = "type")]
    ty: TypeRef,
}

#[derive(Deserialize)]
struct StatusType {
    status: u16,
    #[serde(rename = "type")]
    ty: TypeRef,
}

#[derive(Deserialize)]
struct HttpEntry {
    group: String,
    endpoint: String,
    method: String,
    path: String,
    params: Option<TypeRef>,
    query: Option<TypeRef>,
    headers: Option<TypeRef>,
    payload: Vec<Payload>,
    success: Vec<StatusType>,
    errors: Vec<StatusType>,
}

#[derive(Deserialize)]
struct TaggedVariant {
    value: String,
    def: String,
}

#[derive(Deserialize)]
struct TaggedUnion {
    tag: String,
    variants: Vec<TaggedVariant>,
    #[serde(default)]
    recursive: bool,
}

#[derive(Deserialize)]
struct Manifest {
    rpc: Vec<RpcEntry>,
    http: Vec<HttpEntry>,
    named: BTreeMap<String, TypeRef>,
    #[serde(rename = "taggedUnions")]
    tagged_unions: BTreeMap<String, TaggedUnion>,
}

/// Same name mangling typify applies to definition keys (util.rs `sanitize`, Pascal case).
fn typify_name(def: &str) -> String {
    use heck::ToPascalCase;
    def.replace(|c: char| !(c.is_ascii_alphanumeric() || c == '_'), "-")
        .to_pascal_case()
}

const HEADER: &str = "// @generated by mustr-crates/t3_api/codegen from T3 Code's contracts. DO NOT EDIT.\n// Regenerate with mustr-crates/t3_api/codegen/regen.sh <t3-checkout>.\n";

fn main() -> Result<()> {
    let args: Vec<String> = std::env::args().collect();
    if args.len() != 3 {
        bail!("usage: t3-typify-gen <schema-dir> <out-dir>");
    }
    let schema_dir = PathBuf::from(&args[1]);
    let out_dir = PathBuf::from(&args[2]);
    fs::create_dir_all(&out_dir)?;

    let root: RootSchema = serde_json::from_str(
        &fs::read_to_string(schema_dir.join("t3-api.schema.json")).context("read schema")?,
    )
    .context("parse schema as draft-07 RootSchema")?;
    let manifest: Manifest = serde_json::from_str(
        &fs::read_to_string(schema_dir.join("manifest.json")).context("read manifest")?,
    )?;

    let mut settings = TypeSpaceSettings::default();
    settings
        .with_struct_builder(false)
        .with_derive("PartialEq".to_string())
        .with_map_type("::std::collections::BTreeMap")
        // Effect's JSON number (number | "Infinity" | "-Infinity" | "NaN"): hand-written type.
        .with_replacement("JsNumber", "crate::JsNumber", std::iter::empty());
    // Discriminated unions are emitted by us (tagged.rs), not typify.
    for name in manifest.tagged_unions.keys() {
        let n = typify_name(name);
        settings.with_replacement(&n, format!("crate::tagged::{n}"), std::iter::empty());
    }
    let mut space = TypeSpace::new(&settings);
    space.add_root_schema(root).context("typify")?;

    // Resolve manifest definition names to the Rust idents typify chose.
    let mut idents: BTreeMap<String, String> = BTreeMap::new();
    let mut rust = |t: &TypeRef| -> Result<String> {
        Ok(match t {
            TypeRef::Void => "()".to_string(),
            TypeRef::Never => "crate::Never".to_string(),
            TypeRef::Ref {
                def,
                nullable: true,
            } => {
                format!("Option<{}>", rust_ref(&mut space, &mut idents, def)?)
            }
            TypeRef::Ref {
                def,
                nullable: false,
            } => rust_ref(&mut space, &mut idents, def)?,
        })
    };
    /// Rust path for a definition, as typify named it (memoized).
    fn rust_ref(
        space: &mut TypeSpace,
        idents: &mut BTreeMap<String, String>,
        def: &str,
    ) -> Result<String> {
        if let Some(i) = idents.get(def) {
            return Ok(i.clone());
        }
        let id = space
            .add_type(&Schema::new_ref(format!("#/definitions/{def}")))
            .with_context(|| format!("resolve {def}"))?;
        let name = space.get_type(&id)?.ident().to_string().replace(' ', "");
        let path = if name.starts_with("crate::") {
            name
        } else {
            format!("types::{name}")
        };
        idents.insert(def.to_string(), path.clone());
        Ok(path)
    }

    // ---- tagged.rs --------------------------------------------------------------
    let mut t = String::from(HEADER);
    t.push_str("#![allow(clippy::all)]\nuse crate::types;\n\n");
    for (name, u) in &manifest.tagged_unions {
        let n = typify_name(name);
        // Self-check: typify must resolve this def to our replacement.
        let resolved = rust(&TypeRef::Ref {
            def: name.clone(),
            nullable: false,
        })?;
        if resolved != format!("crate::tagged::{n}") {
            bail!("tagged union {name} resolved to {resolved}; replacement key mismatch");
        }
        let mut used = BTreeMap::new();
        used.insert("Unrecognized".to_string(), ());
        writeln!(
            t,
            "crate::tagged_union! {{\n    /// `{name}`, discriminated by `{tag}`.\n    pub enum {n}: {tag:?} {{",
            tag = u.tag
        )?;
        for v in &u.variants {
            let mut vn = typify_name(&v.value);
            if vn.is_empty() || !vn.chars().next().unwrap().is_ascii_alphabetic() {
                vn = format!("V{vn}");
            }
            let base = vn.clone();
            let mut i = 2;
            while used.insert(vn.clone(), ()).is_some() {
                vn = format!("{base}{i}");
                i += 1;
            }
            let ty = rust(&TypeRef::Ref {
                def: v.def.clone(),
                nullable: false,
            })?;
            let ty = if u.recursive {
                format!("Box<{ty}>")
            } else {
                ty
            };
            writeln!(t, "        {:?} => {vn}({ty}),", v.value)?;
        }
        t.push_str("    }\n}\n");
    }

    // ---- methods.rs -------------------------------------------------------------
    let mut m = String::from(HEADER);
    m.push_str("#![allow(clippy::all)]\nuse crate::{types, HttpEndpoint, RpcMethod};\n\n");
    m.push_str("/// WebSocket RPC methods (Effect RPC over `RpcSerialization.layerJson`).\npub mod rpc {\n    use super::*;\n");
    let mut seen = BTreeMap::new();
    for r in &manifest.rpc {
        let name = pascal(&r.tag);
        if seen.insert(name.clone(), ()).is_some() {
            bail!("duplicate rpc struct name {name}");
        }
        let (p, s, e) = (rust(&r.payload)?, rust(&r.success)?, rust(&r.error)?);
        writeln!(
            m,
            "    /// `{tag}`{stream}\n    #[derive(Debug, Clone, Copy, Default)]\n    pub struct {name};\n    impl RpcMethod for {name} {{\n        const TAG: &'static str = {tag:?};\n        const STREAM: bool = {st};\n        type Payload = {p};\n        type Success = {s};\n        type Error = {e};\n    }}",
            tag = r.tag,
            stream = if r.stream {
                " (stream: `Success` is the chunk element type)"
            } else {
                ""
            },
            st = r.stream,
        )?;
    }
    m.push_str("    /// Every RPC tag the server's `WsRpcGroup` exposes, in declaration order.\n    pub const ALL_TAGS: &[&str] = &[\n");
    for r in &manifest.rpc {
        writeln!(m, "        {:?},", r.tag)?;
    }
    m.push_str("    ];\n}\n\n");

    m.push_str("/// HTTP endpoints (Effect HttpApi). Error bodies per status are exposed as type aliases.\npub mod http {\n    use super::*;\n");
    for h in &manifest.http {
        let name = format!("{}{}", pascal(&h.group), pascal(&h.endpoint));
        let opt = |t: &Option<TypeRef>,
                   rust: &mut dyn FnMut(&TypeRef) -> Result<String>|
         -> Result<String> {
            Ok(match t {
                None => "()".to_string(),
                Some(t) => rust(t)?,
            })
        };
        let params = opt(&h.params, &mut rust)?;
        let query = opt(&h.query, &mut rust)?;
        let headers = opt(&h.headers, &mut rust)?;
        let (req_ct, req) = match h.payload.first() {
            None => ("None".to_string(), "()".to_string()),
            Some(p) => (format!("Some({:?})", p.content_type), rust(&p.ty)?),
        };
        let ok = h.success.iter().find(|s| (200..300).contains(&s.status));
        let (ok_status, resp) = match ok {
            None => (200, "()".to_string()),
            Some(s) => (s.status, rust(&s.ty)?),
        };
        let err_statuses: Vec<String> = h.errors.iter().map(|e| e.status.to_string()).collect();
        writeln!(
            m,
            "    /// `{method} {path}`\n    #[derive(Debug, Clone, Copy, Default)]\n    pub struct {name};\n    impl HttpEndpoint for {name} {{\n        const METHOD: &'static str = {method:?};\n        const PATH: &'static str = {path:?};\n        const REQUEST_CONTENT_TYPE: Option<&'static str> = {req_ct};\n        const SUCCESS_STATUS: u16 = {ok_status};\n        const ERROR_STATUSES: &'static [u16] = &[{errs}];\n        type Params = {params};\n        type Query = {query};\n        type Headers = {headers};\n        type Request = {req};\n        type Response = {resp};\n    }}",
            method = h.method,
            path = h.path,
            errs = err_statuses.join(", "),
        )?;
        for e in &h.errors {
            writeln!(
                m,
                "    pub type {name}Error{} = {};",
                e.status,
                rust(&e.ty)?
            )?;
        }
    }
    m.push_str("}\n\n/// Named types requested explicitly (EXTRA_ROOTS in dump-schemas.ts).\npub mod named {\n    use super::*;\n");
    for (n, t) in &manifest.named {
        writeln!(m, "    pub type {n} = {};", rust(t)?)?;
    }
    m.push_str("}\n");

    // ---- types.rs ---------------------------------------------------------------
    // Generate after resolving manifest refs (resolution can't add types, but be safe).
    // typify does not de-duplicate derived names against definition names; fail early
    // with a readable message instead of a wall of E0428s.
    let mut names: BTreeMap<String, usize> = BTreeMap::new();
    for ty in space.iter_types() {
        let n = ty.name();
        // Only types typify defines (structs/enums/newtypes); skip Option<..>, Vec<..>, etc.
        if !n.contains(':') && !n.contains('<') {
            *names.entry(n).or_default() += 1;
        }
    }
    let dups: Vec<_> = names
        .iter()
        .filter(|(_, n)| **n > 1)
        .map(|(k, _)| k.clone())
        .collect();
    if !dups.is_empty() {
        bail!(
            "typify produced duplicate type names (add a collision rule in dump-schemas.ts): {dups:?}"
        );
    }

    let tokens = space.to_stream();
    let types =
        format!("{HEADER}#![allow(clippy::all, non_camel_case_types, unused_imports)]\n{tokens}");

    // ---- dispatch.rs (tests only): definition name -> JSON round-trip through the Rust type.
    let mut d = String::from(HEADER);
    d.push_str("/// Deserialize `v` as the Rust type generated for definition `def`, then serialize it back.\n");
    d.push_str("pub fn roundtrip(def: &str, v: serde_json::Value) -> Option<Result<serde_json::Value, String>> {\n    Some(match def {\n");
    let mut nullable = std::collections::BTreeSet::new();
    let mut note = |t: &TypeRef| {
        if let TypeRef::Ref {
            def,
            nullable: true,
        } = t
        {
            nullable.insert(def.clone());
        }
    };
    for r in &manifest.rpc {
        [&r.payload, &r.success, &r.error]
            .into_iter()
            .for_each(&mut note);
    }
    for h in &manifest.http {
        h.params
            .iter()
            .chain(&h.query)
            .chain(&h.headers)
            .for_each(&mut note);
        h.payload.iter().for_each(|p| note(&p.ty));
        h.success.iter().chain(&h.errors).for_each(|s| note(&s.ty));
    }
    manifest.named.values().for_each(&mut note);
    for (def, path) in &idents {
        let path = path.replacen("crate::", "t3_api::", 1);
        let path = if path.starts_with("types::") {
            format!("t3_api::{path}")
        } else {
            path
        };
        let path = if nullable.contains(def) {
            format!("Option<{path}>")
        } else {
            path
        };
        writeln!(d, "        {def:?} => rt::<{path}>(v),")?;
    }
    d.push_str("        _ => return None,\n    })\n}\n");

    for (file, src) in [
        ("types.rs", types),
        ("tagged.rs", t),
        ("methods.rs", m),
        ("dispatch.rs", d),
    ] {
        let path = out_dir.join(file);
        fs::write(&path, src)?;
        format_rust(&path)?;
    }
    eprintln!(
        "typify-gen: {} types ({} tagged unions), {} rpc methods, {} http endpoints -> {}",
        space.iter_types().count(),
        manifest.tagged_unions.len(),
        manifest.rpc.len(),
        manifest.http.len(),
        out_dir.display()
    );
    Ok(())
}

/// Pretty-print with prettyplease (no dependency on a rustfmt toolchain component, and
/// output is byte-stable across machines).
fn format_rust(path: &PathBuf) -> Result<()> {
    let src = fs::read_to_string(path)?;
    let (header, body): (Vec<&str>, Vec<&str>) = src
        .lines()
        .partition(|l| l.starts_with("// @generated") || l.starts_with("// Regenerate"));
    let file =
        syn::parse_file(&body.join("\n")).with_context(|| format!("parse {}", path.display()))?;
    fs::write(
        path,
        format!("{}\n{}", header.join("\n"), prettyplease::unparse(&file)),
    )?;
    Ok(())
}

fn pascal(s: &str) -> String {
    s.split(|c: char| !c.is_ascii_alphanumeric())
        .filter(|p| !p.is_empty())
        .map(|p| {
            let mut c = p.chars();
            c.next()
                .map(|f| f.to_ascii_uppercase().to_string() + c.as_str())
                .unwrap_or_default()
        })
        .collect()
}
